#!/usr/bin/env python3
"""Generate MED_charclass.m31: nvim's word-motion character classes for
code points >= 0x100, by probing `w` in a real nvim (the oracle), not from
memory of mbyte.c.

    python3 tests/oracles/gen_charclass.py > MED_charclass.m31

Class ids: 0 blank, 1 punctuation, 2 word, 3 emoji, 4.. script classes in
order of first discovery. Code points below 0x100 are handled by hand in
MED_text (they follow 'iskeyword').
"""
import subprocess, sys, tempfile, os, json

LUA = r'''
local reps = {".", "a", vim.fn.nr2char(0x1F600)}  -- classes 1, 2, 3
local function probe(x, r, q)
  vim.api.nvim_buf_set_lines(0, 0, -1, false, {x .. r .. q})
  vim.api.nvim_win_set_cursor(0, {1, 0})
  vim.cmd("normal! w")
  local col = vim.api.nvim_win_get_cursor(0)[2]
  return col == #x + #r   -- landed on q: x is the same class as r
end
local function is_blank(x)
  vim.api.nvim_buf_set_lines(0, 0, -1, false, {"a" .. x .. "bc"})
  vim.api.nvim_win_set_cursor(0, {1, 0})
  vim.cmd("normal! W")
  local col = vim.api.nvim_win_get_cursor(0)[2]
  return col == 1 + #x
end
local function classify(cp)
  local x = vim.fn.nr2char(cp)
  for i = 1, #reps do
    local r = reps[i]
    local q = (i == 2) and "." or "a"
    if probe(x, r, q) then return i end   -- reps[1] is class 1
  end
  if is_blank(x) then return 0 end
  table.insert(reps, x)
  return #reps
end
local classes = {}
local cur_lo, cur_cls = nil, nil
local out = {}
local function flush(hi)
  if cur_lo then table.insert(out, {cur_lo, hi, cur_cls}) end
end
local last = 0
for cp = 0x100, 0x10FFFF do
  if cp < 0xD800 or cp > 0xDFFF then
    local cls = classify(cp)
    if cur_cls ~= cls or last ~= cp - 1 then
      flush(last)
      cur_lo, cur_cls = cp, cls
    end
    last = cp
  end
end
flush(last)
local f = io.open(arg[1], "w")
f:write(vim.json.encode(out))
f:close()
'''

def main():
    d = tempfile.mkdtemp()
    lua = os.path.join(d, "probe.lua")
    res = os.path.join(d, "out.json")
    open(lua, "w").write(LUA)
    subprocess.run(["nvim", "--headless", "-u", "NONE", "-i", "NONE", "-n", "-l", lua, res], check=True)
    ranges = json.load(open(res))
    print("// Generated by tests/oracles/gen_charclass.py from nvim's own `w` motion. Do not edit.")
    print("// Triples of (first, last, class) for code points >= 0x100; absent => class 2.")
    flat = []
    for lo, hi, cls in ranges:
        if cls != 2:
            flat += [lo, hi, cls]
    print("pub const List<int> RANGES = [")
    line = "   "
    for i in range(0, len(flat), 3):
        item = " %d, %d, %d," % tuple(flat[i:i+3])
        if len(line) + len(item) > 96:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];")

main()
