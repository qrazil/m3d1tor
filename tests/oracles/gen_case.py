#!/usr/bin/env python3
"""Generate engine/MED_case.m31: nvim's upper/lower case mapping for code points
>= 0x80 by probing `toupper()` / `tolower()` in a real nvim (the oracle).

    python3 tests/oracles/gen_case.py > engine/MED_case.m31
"""
import subprocess, tempfile, os, json

LUA = r'''
local up, low = {}, {}
for cp = 0x80, 0x1FFFF do
  if cp < 0xD800 or cp > 0xDFFF then
    local c = vim.fn.nr2char(cp)
    local u = vim.fn.toupper(c)
    local l = vim.fn.tolower(c)
    if u ~= c and vim.fn.strchars(u) == 1 then table.insert(up, {cp, vim.fn.char2nr(u)}) end
    if l ~= c and vim.fn.strchars(l) == 1 then table.insert(low, {cp, vim.fn.char2nr(l)}) end
  end
end
local f = io.open(arg[1], "w")
f:write(vim.json.encode({up = up, low = low}))
f:close()
'''

def main():
    with tempfile.TemporaryDirectory() as d:
        lua = os.path.join(d, "g.lua")
        out = os.path.join(d, "out.json")
        open(lua, "w").write(LUA)
        subprocess.run(["nvim", "--headless", "-u", "NONE", "-i", "NONE", "-n", "-l", lua, out], check=True)
        data = json.load(open(out))
    def flat(pairs):
        return ", ".join(f"{a}, {b}" for a, b in pairs)
    print("// Generated by tests/oracles/gen_case.py from nvim's toupper()/tolower(). Do not edit.")
    print("// Flat sorted (code point, mapped code point) pairs for code points >= 0x80.")
    print(f"const List<int> UP = [{flat(data['up'])}];")
    print(f"const List<int> LOW = [{flat(data['low'])}];")
    print('''
int lookup(List<int> table, int cp) {
    int low = 0;
    int high = table.size() / 2 - 1;
    while (low <= high) {
        int mid = (low + high) / 2;
        int key = table[mid * 2];
        if (key == cp) {
            return table[mid * 2 + 1];
        }
        if (key < cp) {
            low = mid + 1;
        } else {
            high = mid - 1;
        }
    }
    return cp;
}

/// The upper-case form of the single character `ch` (itself when none).
pub str upper(str ch) {
    int cp = ch.chars()[0];
    if (cp >= 97 && cp <= 122) {
        return str.from_chars([cp - 32]);
    }
    if (cp < 128) {
        return ch;
    }
    return str.from_chars([lookup(UP, cp)]);
}

/// The lower-case form of the single character `ch` (itself when none).
pub str lower(str ch) {
    int cp = ch.chars()[0];
    if (cp >= 65 && cp <= 90) {
        return str.from_chars([cp + 32]);
    }
    if (cp < 128) {
        return ch;
    }
    return str.from_chars([lookup(LOW, cp)]);
}''')

main()
