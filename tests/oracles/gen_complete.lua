local cmds = vim.fn.getcompletion('', 'command')
local skip = { EditQuery = true, Inspect = true, InspectTree = true, Open = true }
local out = {}
local function q(s) return '"' .. s:gsub('\\', '\\\\'):gsub('"', '\\"') .. '"' end
local function list(name, items)
  out[#out + 1] = 'pub const List<str> ' .. name .. ' = ['
  local line = '   '
  for i, v in ipairs(items) do
    local piece = ' ' .. q(v) .. (i < #items and ',' or '')
    if #line + #piece > 110 then out[#out + 1] = line; line = '   ' end
    line = line .. piece
  end
  out[#out + 1] = line
  out[#out + 1] = '];'
  out[#out + 1] = ''
end
local keep = {}
for _, c in ipairs(cmds) do if not skip[c] and #c > 0 then keep[#keep + 1] = c end end
local opts = vim.fn.getcompletion('', 'option')
local info = vim.api.nvim_get_all_options_info()
local o, b, sh = {}, {}, {}
for _, n in ipairs(opts) do
  if info[n] then o[#o + 1] = n; sh[#sh + 1] = info[n].shortname or ''; if info[n].type == 'boolean' then b[#b + 1] = n end
  else o[#o + 1] = n; sh[#sh + 1] = '' end
end
out[#out + 1] = '// Generated by tests/oracles/gen_complete.lua from nvim 0.11\'s own lists. Do not edit.'
out[#out + 1] = '// The ex command names and option names command-line completion offers.'
out[#out + 1] = ''
list('COMMANDS', keep)
list('OPTIONS', o)
list('BOOL_OPTIONS', b)
list('OPTION_SHORT_NAMES', sh)
local f = io.open(arg[1], 'w'); f:write(table.concat(out, '\n')); f:close()
